package cmd

import (
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"testing"

	"github.com/boxboxjason/gitlab-achievements/internal/config"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

const (
	// updateDocsEnv, when set, makes TestCLIReference rewrite the generated page instead of comparing it.
	updateDocsEnv = "UPDATE_DOCS"

	docsContentDir    = "../docs/content/docs"
	cliReferenceFile  = "cli-reference.md"
	configurationFile = "configuration.md"

	docsFilePermission = 0o600
	docsDirPermission  = 0o750
)

// subcommandDocs names the page documenting each subcommand, where its own flags must appear.
//
//nolint:gochecknoglobals // test fixture
var subcommandDocs = map[string]string{
	"backfill":  "backfill.md",
	"reconcile": "reconciliation.md",
	"uninstall": "uninstall.md",
}

// envVarPatterns find the environment variables root.go reads, whichever helper reads them.
//
//nolint:gochecknoglobals // compiled once
var envVarPatterns = []*regexp.Regexp{
	regexp.MustCompile(`(?:Getenv|OrDefault)\("([A-Z][A-Z0-9_]*)"`),
	regexp.MustCompile(`secretFlag\([^,]+,[^,]+,\s*"[^"]+",\s*"([A-Z][A-Z0-9_]*)"`),
	regexp.MustCompile(`\benv[A-Z]\w*\s*=\s*"([A-Z][A-Z0-9_]*)"`),
}

// cliEnvVars returns the environment variables the CLI configuration is read from.
func cliEnvVars(t *testing.T) []string {
	t.Helper()

	source, err := os.ReadFile("root.go")
	if err != nil {
		t.Fatalf("reading root.go: %v", err)
	}

	var names []string

	for _, pattern := range envVarPatterns {
		for _, match := range pattern.FindAllStringSubmatch(string(source), -1) {
			if !slices.Contains(names, match[1]) {
				names = append(names, match[1])
			}
		}
	}

	return names
}

// newDocumentedRootCmd builds the command tree the way the documentation describes it:
// without any configuration inherited from the environment.
func newDocumentedRootCmd(t *testing.T) *cobra.Command {
	t.Helper()

	// Flag defaults are read from the environment.
	for _, name := range cliEnvVars(t) {
		t.Setenv(name, "")
	}

	rootCmd := buildRootCmd(&config.Config{})
	rootCmd.InitDefaultHelpFlag()
	rootCmd.InitDefaultVersionFlag()

	for _, command := range rootCmd.Commands() {
		command.InitDefaultHelpFlag()
	}

	return rootCmd
}

// renderCLIReference renders the help of every command as a documentation page.
// Subcommands share the root command's flags, which are only listed once.
func renderCLIReference(rootCmd *cobra.Command) string {
	var page strings.Builder

	page.WriteString("---\ntitle: CLI reference\nweight: 150\n---\n\n")
	page.WriteString("<!-- Code generated by TestCLIReference (run `make docs-generate`); DO NOT EDIT. -->\n\n")
	page.WriteString("{{< callout type=\"info\" >}}\nThis page is generated from the CLI definition, so it always matches the released flags. " +
		"Every flag also has an environment variable, listed in [Configuration]({{< relref \"/docs/configuration\" >}}).\n{{< /callout >}}\n")

	page.WriteString("\n## " + rootCmd.CommandPath() + "\n\n")
	page.WriteString(strings.TrimSpace(rootCmd.Long) + "\n\n")
	page.WriteString("```text\n" + strings.TrimSpace(rootCmd.UsageString()) + "\n```\n")

	for _, command := range rootCmd.Commands() {
		page.WriteString("\n## " + command.CommandPath() + "\n\n")
		page.WriteString(strings.TrimSpace(command.Long) + "\n\n")
		page.WriteString("```text\nUsage:\n  " + command.UseLine() + "\n\nFlags:\n")
		page.WriteString(strings.TrimRight(command.LocalNonPersistentFlags().FlagUsages(), "\n") + "\n```\n\n")
		page.WriteString("It also takes every flag of [" + rootCmd.Name() + "](#" + rootCmd.Name() + ").\n")
	}

	return page.String()
}

// TestCLIReference fails when the generated CLI reference no longer matches the CLI.
// Regenerate it with `make docs-generate`.
func TestCLIReference(t *testing.T) {
	want := renderCLIReference(newDocumentedRootCmd(t))
	path := filepath.Join(docsContentDir, cliReferenceFile)

	if os.Getenv(updateDocsEnv) != "" {
		if err := os.MkdirAll(filepath.Dir(path), docsDirPermission); err != nil {
			t.Fatalf("creating the docs directory: %v", err)
		}

		if err := os.WriteFile(path, []byte(want), docsFilePermission); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}

		return
	}

	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v (run `make docs-generate`)", path, err)
	}

	if string(got) != want {
		t.Fatalf("%s is out of date, run `make docs-generate` and commit the result", path)
	}
}

func readDocsPage(t *testing.T, name string) string {
	t.Helper()

	content, err := os.ReadFile(filepath.Join(docsContentDir, name))
	if err != nil {
		t.Fatalf("reading the %s documentation page: %v", name, err)
	}

	return string(content)
}

// TestDocsCoverEveryFlag fails when a flag is added without being documented: the
// shared ones in the configuration page, a subcommand's own ones in its page.
func TestDocsCoverEveryFlag(t *testing.T) {
	rootCmd := newDocumentedRootCmd(t)
	configuration := readDocsPage(t, configurationFile)

	rootCmd.PersistentFlags().VisitAll(func(flag *pflag.Flag) {
		if !strings.Contains(configuration, "`--"+flag.Name+"`") {
			t.Errorf("flag --%s is not documented in docs/content/docs/%s", flag.Name, configurationFile)
		}
	})

	for _, command := range rootCmd.Commands() {
		if !strings.Contains(configuration, "`"+command.CommandPath()+"`") {
			t.Errorf("subcommand %s is not listed in docs/content/docs/%s", command.Name(), configurationFile)
		}

		page, ok := subcommandDocs[command.Name()]
		if !ok {
			t.Errorf("subcommand %s has no documentation page, add it to subcommandDocs", command.Name())

			continue
		}

		content := readDocsPage(t, page)

		command.LocalNonPersistentFlags().VisitAll(func(flag *pflag.Flag) {
			if flag.Name != "help" && !strings.Contains(content, "--"+flag.Name) {
				t.Errorf("flag --%s of %s is not documented in docs/content/docs/%s", flag.Name, command.Name(), page)
			}
		})
	}
}

// TestDocsCoverEveryEnvVar fails when an environment variable is read without being documented.
func TestDocsCoverEveryEnvVar(t *testing.T) {
	configuration := readDocsPage(t, configurationFile)
	names := cliEnvVars(t)

	// Every shared flag has its environment variable: finding fewer means the patterns missed one.
	flagCount := 0

	newDocumentedRootCmd(t).PersistentFlags().VisitAll(func(*pflag.Flag) { flagCount++ })

	if len(names) != flagCount {
		t.Fatalf("found %d environment variables in root.go for %d flags, envVarPatterns is out of date: %v", len(names), flagCount, names)
	}

	for _, name := range names {
		if !strings.Contains(configuration, "`"+name+"`") {
			t.Errorf("environment variable %s is not documented in docs/content/docs/%s", name, configurationFile)
		}
	}
}
